"""Generate a POV portal-setup script that uses the public Logic.Monitor PowerShell module
(https://github.com/logicmonitor/lm-powershell-module, MPL-2.0).

The app never changes a portal itself. The script is reviewed and run by a person:

* Dry run by default: connects, runs read-only checks, prints what it would change.
  ``-Apply`` makes the changes.
* No credentials are embedded. It uses environment variables or a cached credential.
* Toolkit LogicModules are downloaded at run time from the reviewed, pinned commit of
  their public repository. A module that already exists (by name) is skipped, and JSON
  imports also use ``-HandleConflict ERROR``, so existing customer modules are never
  overwritten.

Cmdlets and parameters used (verified in the module source at the pinned commit):
Connect-LMAccount (-AccessId/-AccessKey/-AccountName, -BearerToken/-AccountName,
-UseCachedCredential), Disconnect-LMAccount, Get-LMCollector, Get-LMDeviceGroup -Name, Get-LMDatasource -Name,
Get-LMLogSource -Name,
New-LMDeviceGroup (-Name, -Description, -Properties, -ParentGroupId),
Import-LMLogicModuleFromFile (-FilePath, -Type, -Format, -HandleConflict).
"""

from __future__ import annotations

import re

from ..knowledge import KnowledgeBase, ToolkitItem
from ..models import Account, Deal, PovPlan, utcnow
from .pov_readiness import group_name

IMPORT_TYPE = {"datasource": "datasources", "logsource": "logsources"}
_CURLY_SINGLE = re.compile("[‘’‚‛]")
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")


class ScriptError(ValueError):
    pass


def ps_str(value: object) -> str:
    """PowerShell single-quoted literal. Curly single quotes are also delimiters in
    PowerShell, so they are normalised before doubling."""
    text = _CONTROL.sub(" ", _CURLY_SINGLE.sub("'", str(value)))
    return "'" + text.replace("'", "''") + "'"


def resolve_toolkit(kb: KnowledgeBase, toolkit_ids: list[str]) -> list[ToolkitItem]:
    """Selected items plus everything they require, dependencies first."""
    unknown = [t for t in toolkit_ids if t not in kb.toolkit]
    if unknown:
        raise ScriptError(f"Unknown toolkit item(s): {', '.join(unknown)}")
    ordered: list[ToolkitItem] = []

    def add(item_id: str) -> None:
        item = kb.toolkit[item_id]
        for dep in item.requires:
            add(dep)
        if item not in ordered:
            ordered.append(item)

    for t in toolkit_ids:
        add(t)
    return ordered


def generate_setup_script(
    kb: KnowledgeBase,
    *,
    plan: PovPlan,
    deal: Deal,
    account: Account,
    toolkit_ids: list[str],
    include_subgroups: bool = True,
) -> str:
    items = resolve_toolkit(kb, toolkit_ids)
    scripted = [i for i in items if i.import_ == "powershell"]
    manual = [i for i in items if i.import_ == "manual"]
    group = group_name(plan, account)
    subgroups = []
    if include_subgroups:
        for tag in deal.technical_context:
            ctx = kb.context_tags.get(tag)
            if ctx and ctx.portal_group and ctx.portal_group not in subgroups:
                subgroups.append(ctx.portal_group)
    ps_module = kb.ecosystem.project("lm_powershell_module")
    properties = {
        "pov.title": plan.title,
        "pov.start": plan.start_date.isoformat() if plan.start_date else "",
        "pov.end": plan.end_date.isoformat() if plan.end_date else "",
    }
    sources = sorted({(i.project, kb.ecosystem.project(i.project).repo, kb.ecosystem.project(i.project).commit,
                       kb.ecosystem.project(i.project).license) for i in items})

    out: list[str] = []
    w = out.append
    w("<#")
    w(".SYNOPSIS")
    w(f"    POV portal setup: {plan.title} ({account.name})")
    w(".DESCRIPTION")
    w(f"    Generated by SE Demo & POV Builder on {utcnow():%Y-%m-%d %H:%M} UTC. REVIEW BEFORE RUNNING.")
    w("")
    w("    Default is a DRY RUN: connects, runs read-only checks and prints what it would change.")
    w("    Re-run with -Apply to make the changes.")
    w("")
    w(f"    Requires the Logic.Monitor PowerShell module ({ps_module.license}, {ps_module.repo}):")
    w(f"        {ps_module.install}")
    w("")
    w("    No credentials are stored in this script. Provide them with one of:")
    w("      - LM_ACCOUNT plus LM_ACCESS_ID and LM_ACCESS_KEY environment variables (LMv1 API token)")
    w("      - LM_ACCOUNT plus LM_BEARER_TOKEN environment variables")
    w("      - a cached credential created with New-LMCachedAccount")
    if sources:
        w("")
        w("    Downloaded at run time from public repositories (their own licences apply):")
        for _, repo, commit, lic in sources:
            w(f"      - {repo} @ {commit[:12]} ({lic})")
    w("#>")
    w("[CmdletBinding()]")
    w("param(")
    w("    [switch]$Apply,")
    w("    [string]$AccountName = $env:LM_ACCOUNT")
    w(")")
    w("#Requires -Modules Logic.Monitor")
    w("Set-StrictMode -Version Latest")
    w("$ErrorActionPreference = 'Stop'")
    w("")
    w(f"$PovGroupName = {ps_str(group)}")
    w(f"$PovGroupDescription = {ps_str(f'POV: {plan.title} ({deal.name})')}")
    w("$PovGroupProperties = @{")
    for key, value in properties.items():
        w(f"    {ps_str(key)} = {ps_str(value)}")
    w("}")
    w("$SubGroups = @(" + ", ".join(ps_str(s) for s in subgroups) + ")")
    w("$Toolkit = @(")
    for i in scripted:
        w(f"    @{{ Id = {ps_str(i.id)}; Title = {ps_str(i.title)}; Url = {ps_str(kb.ecosystem.raw_url(i))}; "
          f"ModuleName = {ps_str(i.module_name)}; Type = {ps_str(IMPORT_TYPE[i.kind])}; Format = {ps_str(i.format)} }}")
    w(")")
    w("$ManualSteps = @(")
    for i in manual:
        w(f"    {ps_str(f'{i.title}: {i.manual_steps} Source: {kb.ecosystem.source_url(i)}')}")
    for i in scripted:
        if i.manual_steps:
            w(f"    {ps_str(f'{i.title}: {i.manual_steps}')}")
    w(")")
    w("")
    w(_BODY)
    return "\n".join(out) + "\n"


_BODY = r"""function Invoke-Step {
    param([string]$Description, [scriptblock]$Action)
    if ($Apply) {
        Write-Host "[APPLY] $Description"
        & $Action
    }
    else {
        Write-Host "[DRY RUN] Would: $Description"
    }
}

# --- 1. Connect ----------------------------------------------------------------------
if ($env:LM_ACCESS_ID -and $env:LM_ACCESS_KEY) {
    if (-not $AccountName) { throw 'Set LM_ACCOUNT or pass -AccountName.' }
    Connect-LMAccount -AccessId $env:LM_ACCESS_ID -AccessKey $env:LM_ACCESS_KEY -AccountName $AccountName
}
elseif ($env:LM_BEARER_TOKEN) {
    if (-not $AccountName) { throw 'Set LM_ACCOUNT or pass -AccountName.' }
    Connect-LMAccount -BearerToken $env:LM_BEARER_TOKEN -AccountName $AccountName
}
else {
    Connect-LMAccount -UseCachedCredential
}

$tempDir = Join-Path ([IO.Path]::GetTempPath()) ('sepb-' + [guid]::NewGuid().ToString())
try {
    # --- 2. Read-only checks --------------------------------------------------------
    $collectors = @(Get-LMCollector)
    $down = @($collectors | Where-Object { $_.isDown })
    Write-Host "Collectors: $($collectors.Count) total, $($down.Count) down"
    if ($collectors.Count -eq 0) {
        Write-Warning 'No collectors found. Install a collector before onboarding resources.'
    }

    $script:PovGroupId = $null
    $existing = @(Get-LMDeviceGroup -Name $PovGroupName | Where-Object { $_.parentId -eq 1 })
    if ($existing.Count -gt 0) {
        $script:PovGroupId = $existing[0].id
        Write-Host "Resource group '$PovGroupName' already exists (id $($script:PovGroupId)); it will be reused."
    }

    # --- 3. Resource groups ---------------------------------------------------------
    if (-not $script:PovGroupId) {
        Invoke-Step "Create resource group '$PovGroupName' under the root group" {
            $groupArgs = @{ Name = $PovGroupName; Description = $PovGroupDescription; Properties = $PovGroupProperties; ParentGroupId = 1 }
            $created = New-LMDeviceGroup @groupArgs
            $script:PovGroupId = $created.id
        }
    }
    foreach ($subGroup in $SubGroups) {
        # Read-only check before Invoke-Step, so a dry run doesn't offer to create existing subgroups.
        $child = @()
        if ($script:PovGroupId) {
            $child = @(Get-LMDeviceGroup -Name $subGroup | Where-Object { $_.parentId -eq $script:PovGroupId })
        }
        if ($child.Count -gt 0) {
            Write-Host "Resource group '$PovGroupName/$subGroup' already exists (id $($child[0].id)); skipped"
            continue
        }
        Invoke-Step "Create resource group '$PovGroupName/$subGroup'" {
            if (-not $script:PovGroupId) { throw 'POV resource group id is unknown.' }
            New-LMDeviceGroup -Name $subGroup -ParentGroupId $script:PovGroupId | Out-Null
        }
    }

    # --- 4. Toolkit LogicModules (pinned public sources) ----------------------------
    $existsCmd = @{ datasources = 'Get-LMDatasource'; logsources = 'Get-LMLogSource' }
    foreach ($item in $Toolkit) {
        # Never overwrite a module that already exists in the customer's portal.
        if (@(& $existsCmd[$item.Type] -Name $item.ModuleName).Count -gt 0) {
            Write-Host "$($item.Type) '$($item.ModuleName)' already exists; skipped"
            continue
        }
        Invoke-Step "Import $($item.Type) '$($item.Title)' from $($item.Url)" {
            New-Item -ItemType Directory -Path $tempDir -Force | Out-Null
            $file = Join-Path $tempDir ('{0}.{1}' -f $item.Id, $item.Format)
            Invoke-WebRequest -Uri $item.Url -OutFile $file
            $importArgs = @{ FilePath = $file; Type = $item.Type; Format = $item.Format }
            if ($item.Format -eq 'json') { $importArgs.HandleConflict = 'ERROR' }
            Import-LMLogicModuleFromFile @importArgs
        }
    }

    # --- 5. Manual steps --------------------------------------------------------------
    if ($ManualSteps.Count -gt 0) {
        Write-Host ''
        Write-Host 'Manual steps (not automated by this script):'
        foreach ($step in $ManualSteps) { Write-Host " - $step" }
    }
    if (-not $Apply) {
        Write-Host ''
        Write-Host 'Dry run complete. Review the output, then re-run with -Apply to make these changes.'
    }
}
finally {
    if (Test-Path $tempDir) { Remove-Item -Recurse -Force $tempDir }
    Disconnect-LMAccount
}"""
